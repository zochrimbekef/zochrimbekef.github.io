// רמות: w = כמה מילים בערך, ms = כמה זמן כל מילה על המסך, tg = כמה מילות מטרה, per = כמה פעמים כל מטרה, dec = כמה משפטים מטעים לכל מטרה
export const LEVELS2 = [null,
  { w: 30, ms: 820, tg: 1, per: 2, dec: 0 },
  { w: 45, ms: 760, tg: 1, per: 3, dec: 0 },
  { w: 60, ms: 700, tg: 2, per: 2, dec: 0 },
  { w: 75, ms: 650, tg: 2, per: 2, dec: 1 },
  { w: 90, ms: 600, tg: 2, per: 3, dec: 2 },
];
export const MAX2 = 5, ROUNDS2 = 3;
const PFX = /^[והבלשמכ]{0,3}$/;
const clean = w => w.replace(/[.,?!:;"׳״]/g, '');
/** איזו מילת מטרה זו (אינדקס), או -1. "לבמה", "והמקלדת" = מטרה. "בהמה", "מקלחת" = לא */
export function matchTarget(word, targets) {
  const c = clean(word);
  return targets.findIndex(t => c.endsWith(t) && PFX.test(c.slice(0, c.length - t.length)));
}
/** בונה הסבר לרמה: מילים, מטרות, ומיקומי המטרות */
export function build(level, avoidWorld) {
  const L = LEVELS2[level], mix = a => [...a].sort(() => Math.random() - 0.5);
  const pool = WORLDS.filter(w => w.id !== avoidWorld), W = pool[Math.floor(Math.random() * pool.length)];
  const T = mix(W.t).slice(0, L.tg), targets = T.map(t => t.w);
  const parts = [...T.flatMap(t => mix(t.s).slice(0, L.per)), ...T.flatMap(t => mix(t.ds).slice(0, L.dec))];
  let words = parts.join(' ').split(/\s+/).length;
  for (const s of mix(W.n)) { if (words >= L.w) break; parts.push(s); words += s.split(/\s+/).length; }
  const text = mix(parts).join(' ').split(/\s+/);
  return { world: W.id, name: W.name, targets, decoys: L.dec ? T.map(t => t.d) : [], words: text, ms: L.ms, hits: text.map(w => matchTarget(w, targets)) };
}
/** בדיקה למפתח: משפט רגיל או מטעה שמכיל בטעות מטרה, או משפט מטרה בלי המטרה */
export function check() {
  const bad = [];
  for (const W of WORLDS) {
    const tg = W.t.map(t => t.w);
    for (const s of [...W.n, ...W.t.flatMap(t => t.ds)]) if (s.split(/\s+/).some(w => matchTarget(w, tg) >= 0)) bad.push(W.id + ': ' + s);
    for (const t of W.t) for (const s of t.s) if (!s.split(/\s+/).some(w => matchTarget(w, [t.w]) >= 0)) bad.push(W.id + ' חסר ' + t.w + ': ' + s);
  }
  return bad;
}
